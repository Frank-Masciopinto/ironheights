def fill(text: str, ctx: dict) -> str:
    for key, value in ctx.items():
        text = text.replace("«" + key + "»", str(value))
    if "«" in text:
        raise SystemExit(f"unfilled placeholder in: {text}")
    return text


def paragraphs(sentences: list[str]) -> str:
    if len(sentences) <= 2:
        return " ".join(sentences) + "\n"
    mid = max(1, len(sentences) // 2)
    return " ".join(sentences[:mid]) + "\n\n" + " ".join(sentences[mid:]) + "\n"


def numbered(sentences: list[str]) -> str:
    return "".join(f"{index}. {sentence}\n" for index, sentence in enumerate(sentences, 1))


