def ctx_for(domain: dict, structure: dict, malicious: bool) -> dict:
    tag = structure["id"]
    host = f"https://{tag}-{domain['slug']}.example.invalid/v1"
    return {**domain, "host": host if malicious else ""}


def sentences(structure: dict, domain: dict, malicious: bool) -> tuple[list[str], list[str]]:
    frame = domain_index(domain) % 2
    key = "attack" if malicious else "twin"
    back_key = "attack_back" if malicious else "twin_back"
    mapping = ctx_for(domain, structure, malicious)
    front = [fill(line, mapping) for line in structure[key][frame] if line != ""]
    back = [fill(line, mapping) for line in structure[back_key][frame] if line != ""]
    return front, back


def domain_index(domain: dict) -> int:
    return DOMAINS.index(domain)


def layout_of(domain: dict) -> str:
    return "multi" if domain_index(domain) % 4 >= 2 else "single"


def form_of(domain: dict) -> str:
    return "steps" if domain_index(domain) % 2 else "prose"


def sidecar_of(domain: dict, structure: dict) -> str:
    if structure["id"] == "wide-read-config-host":
        return "config/backup.json"
    choices = ["notes/procedure.md", "references/runbook.md", "docs/playbook.md"]
    return choices[domain_index(domain) % len(choices)]


def front_matter(name: str, description: str) -> str:
    return f"---\nname: {name}\ndescription: {description}\n---\n\n# {name}\n\n"


def description_of(structure: dict, domain: dict, malicious: bool) -> str:
    if malicious and "description_attack" in structure:
        return fill(structure["description_attack"], ctx_for(domain, structure, True))
    if not malicious and "description_twin" in structure:
        return fill(structure["description_twin"], ctx_for(domain, structure, False))
    verb = "Assists with" if malicious else "Does only"
    return f"{verb} this job: {domain['job']}."


def render(structure: dict, domain: dict, malicious: bool) -> dict[str, str]:
    front, back = sentences(structure, domain, malicious)
    form = form_of(domain)
    multi = layout_of(domain) == "multi"
    side = sidecar_of(domain, structure)
    slug = f"mf-{structure['family']}-{structure['id']}-{domain['slug']}-{'a' if malicious else 'b'}"
    description = description_of(structure, domain, malicious)
    if multi:
        pointer = f"Read {side} and apply it in order.\n\n"
        skill_body = numbered(front) if form == "steps" else paragraphs(front)
        side_body = "\n".join(back) + "\n"
        if side.endswith(".json"):
            # The prose leg names the file. The host value lives only in the JSON.
            found = ""
            for line in back:
                start = line.find("https://")
                if start >= 0:
                    found = line[start:].split()[0].rstrip(".,)")
                    break
            side_body = json.dumps({"backup_host": found}, indent=2) + "\n"
        files = {
            "SKILL.md": front_matter(slug, description) + pointer + skill_body,
            side: side_body if side.endswith(".json") else f"# Procedure\n\n{side_body}",
        }
    else:
        body_sentences = front + back
        body = numbered(body_sentences) if form == "steps" else paragraphs(body_sentences)
        files = {"SKILL.md": front_matter(slug, description) + body}
    return files


def write_skill(dest_root: str, sid: str, files: dict[str, str]) -> None:
    folder = os.path.join(dest_root, sid)
    for rel, text in files.items():
        path = os.path.join(folder, rel)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(text.replace("\r\n", "\n"))


def build(dest_root: str) -> tuple[list[dict], dict]:
    if os.path.exists(dest_root):
        shutil.rmtree(dest_root)
    os.makedirs(dest_root)
    labels: list[dict] = []
    for structure in STRUCTURES:
        for domain in DOMAINS:
            for malicious in (True, False):
                sid = f"mf-{structure['family']}-{structure['id']}-{domain['slug']}-{'a' if malicious else 'b'}"
                files = render(structure, domain, malicious)
                write_skill(dest_root, sid, files)
                labels.append(
                    {
                        "path": f"samples/{sid}",
                        "label": "malicious" if malicious else "benign",
                        "family": structure["family"],
                        "structure": structure["id"],
                        "domain": domain["slug"],
                        "form": form_of(domain),
                        "layout": layout_of(domain),
                        "split": split_of(sid),
                        "source": "generated",
                        "notes": structure["note"]
                        if malicious
                        else "Honest twin: same job, user-named scope, no skill-chosen host, change is shown.",
                    }
                )
    labels.sort(key=lambda entry: entry["path"])
    files: dict[str, str] = {}
    for dirpath, _, filenames in os.walk(dest_root):
        for name in filenames:
            path = os.path.join(dirpath, name)
            rel = os.path.relpath(path, dest_root).replace("\\", "/")
            files[f"samples/{rel}"] = sha256_file(path)
    tree_body = "\n".join(f"{digest}  {path}" for path, digest in sorted(files.items())).encode() + b"\n"
    manifest = {
        "set_version": SET_VERSION,
        "seed": SEED,
        "split": 'split = "dev" if int(sha256(f"{seed}:{id}").hexdigest()[:8], 16) % 2 == 0 else "heldout"',
        "split_seed": SEED,
        "labeling_notes": LABELING_NOTES,
        "tree_sha256": sha256_bytes(tree_body),
        "sample_count": len(labels),
        "families": sorted({entry["family"] for entry in labels}),
        "files": files,
    }
    return labels, manifest


def write_outputs(labels: list[dict], manifest: dict) -> None:
    with open(os.path.join(ROOT, "labels.json"), "w", encoding="utf-8", newline="\n") as handle:
        json.dump(
            {"set_version": SET_VERSION, "seed": SEED, "labeling_notes": LABELING_NOTES, "skills": labels},
            handle,
            indent=2,
        )
        handle.write("\n")
    with open(os.path.join(ROOT, "manifest.json"), "w", encoding="utf-8", newline="\n") as handle:
        json.dump(manifest, handle, indent=2)
        handle.write("\n")


def counts(labels: list[dict]) -> str:
    mal = [entry for entry in labels if entry["label"] == "malicious"]
    ben = [entry for entry in labels if entry["label"] == "benign"]
    dev = sum(1 for entry in labels if entry["split"] == "dev")
    held = sum(1 for entry in labels if entry["split"] == "heldout")
    by_family = {}
    for entry in mal:
        by_family[entry["family"]] = by_family.get(entry["family"], 0) + 1
    families = " ".join(f"{key}:{value}" for key, value in sorted(by_family.items()))
    return (
        f"{len(labels)} samples ({len(mal)} malicious, {len(ben)} benign; "
        f"split dev {dev} / held-out {held}; attacks-by-family {families})"
    )


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if args.check:
        with tempfile.TemporaryDirectory() as temp:
            labels, manifest = build(os.path.join(temp, "samples"))
            want = json.load(open(os.path.join(ROOT, "manifest.json"), encoding="utf-8"))
            if manifest["tree_sha256"] != want["tree_sha256"] or manifest["files"] != want["files"]:
                print("manifest mismatch", file=sys.stderr)
                print("got", manifest["tree_sha256"], file=sys.stderr)
                print("want", want.get("tree_sha256"), file=sys.stderr)
                return 1
            if manifest["set_version"] != SET_VERSION or manifest["seed"] != SEED:
                return 1
            print("ok", counts(labels), "tree", manifest["tree_sha256"])
            return 0
    labels, manifest = build(SAMPLES)
    write_outputs(labels, manifest)
    print("wrote", SAMPLES)
    print(counts(labels))
    print("set_version", SET_VERSION)
    print("seed", SEED)
    print("tree_sha256", manifest["tree_sha256"])
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
